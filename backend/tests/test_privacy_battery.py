@pytest.mark.parametrize("text,hide,keep", CASES, ids=[c[0][:40] for c in CASES])
def test_battery(text, hide, keep):
    masked = PrivacyGuard(text).masked_text()
    assert [h for h in hide if h in masked] == [], masked
    assert [k for k in keep if k not in masked] == [], masked
